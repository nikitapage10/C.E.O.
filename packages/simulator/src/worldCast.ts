import { RELATIONSHIP_KINDS, ROOMS, ROOM_IDS, type RelationshipKind, type RoomId } from "@ceo/core";
import { SAMPLE_AGENTS } from "./agents.ts";
import { defaultCast } from "./cast.ts";
import { AGENT_QUIPS, CHRONICLE_QUIPS, SHIPPED_REMARKS, SUBMIND_CONDUCT } from "./quips.ts";

/**
 * The cast as the hourly world step sees it (api/_world, docs/WORLD.md): who everyone is, where they live, how they
 * talk, and who they have history with. The step runs as a Vercel function, which can't load this package (it is
 * TypeScript the browser bundle compiles), so `npm run world:cast` writes this out as plain data in
 * `api/_world/cast.ts`, and a test fails when that file falls behind the cast.
 */

export interface WorldCastMember {
  id: string;
  name: string;
  role: string;
  room: RoomId;
  /** True for a Skippy submind, the lead of its room. */
  lead: boolean;
  traits: string[];
  bio: string;
  catchphrase: string;
  /** A few of their own lines, so the writer catches the voice. */
  voice: string[];
}

export interface WorldCastRelationship {
  a: string;
  b: string;
  kind: RelationshipKind;
  note: string;
}

export interface WorldCast {
  rooms: { id: RoomId; name: string }[];
  kinds: RelationshipKind[];
  members: WorldCastMember[];
  relationships: WorldCastRelationship[];
  /** Scripted stand-ins, for steps that run without Claude. */
  scripted: {
    quips: Record<string, string[]>;
    conduct: Record<string, string[]>;
    shipped: Record<string, string[]>;
    summaries: string[];
  };
}

const VOICE_LINES = 4;

export function worldCast(): WorldCast {
  const cast = defaultCast();
  const members: WorldCastMember[] = SAMPLE_AGENTS.map((a) => {
    const p = cast.profiles[a.id]!;
    return {
      id: a.id,
      name: p.name,
      role: p.role,
      room: a.home.room,
      lead: a.script === "submindConduct",
      traits: p.personality.traits,
      bio: p.personality.bio,
      catchphrase: p.personality.catchphrase,
      voice: (AGENT_QUIPS[a.id] ?? []).slice(0, VOICE_LINES),
    };
  });
  return {
    rooms: ROOM_IDS.map((id) => ({ id, name: ROOMS[id].name })),
    kinds: [...RELATIONSHIP_KINDS],
    members,
    relationships: cast.relationships.map((r) => ({ a: r.a, b: r.b, kind: r.kind, note: r.note ?? "" })),
    scripted: { quips: AGENT_QUIPS, conduct: SUBMIND_CONDUCT, shipped: SHIPPED_REMARKS, summaries: CHRONICLE_QUIPS },
  };
}

/** The generated module's text: `api/_world/cast.ts`. */
export function renderWorldCast(): string {
  return `/**
 * The cast as the hourly world step sees it. GENERATED by \`npm run world:cast\` from packages/simulator
 * (cast.ts, agents.ts, quips.ts, worldCast.ts): don't edit by hand, edit the cast and run it again. A test fails when
 * this file falls behind.
 */

import type { WorldCast } from "./types.js";

export const WORLD_CAST: WorldCast = ${JSON.stringify(worldCast(), null, 2)};
`;
}
