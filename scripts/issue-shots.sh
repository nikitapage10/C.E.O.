#!/usr/bin/env bash
# Attach screenshots to a Foundry issue, so the issue keeps a picture history of the work (docs/FOUNDRY.md, "The trail
# on every issue"). GitHub's API can't upload images to an issue, so the pictures go on the `foundry-shots` branch
# (orphan, never merged, never deployed) as small JPEGs under <issue>/, and a "Trail · Pictures" comment shows them.
#
#   scripts/issue-shots.sh <issue> "<what they show>" shot1.png [shot2.png ...]
set -euo pipefail

issue="$1"; note="$2"; shift 2
repo="nikitapage10/C.E.O."
branch="foundry-shots"
root="$(git rev-parse --show-toplevel)"
work="$(mktemp -d)"
trap 'git -C "$root" worktree remove --force "$work" >/dev/null 2>&1 || true; rm -rf "$work"' EXIT

git -C "$root" fetch -q origin "$branch" 2>/dev/null || true
if git -C "$root" rev-parse -q --verify "origin/$branch" >/dev/null; then
  git -C "$root" worktree add -q --detach "$work" "origin/$branch"
else
  git -C "$root" worktree add -q --detach "$work"
  git -C "$work" checkout -q --orphan "$branch"
  git -C "$work" rm -rfq . >/dev/null
  printf 'Screenshots for Foundry issues, one folder per issue. Never merged; see scripts/issue-shots.sh.\n' > "$work/README.md"
fi

mkdir -p "$work/$issue"
body="**Trail · Pictures:** $note"$'\n'
for f in "$@"; do
  name="$(date -u +%Y%m%d-%H%M%S)-$(basename "${f%.*}").jpg"
  # Shrink to 1600 px wide JPEGs: a picture history shouldn't weigh down the repo.
  convert "$f" -resize '1600x>' -quality 82 "$work/$issue/$name"
  body+=$'\n'"![$(basename "${f%.*}")](https://raw.githubusercontent.com/$repo/$branch/$issue/$name)"
done

git -C "$work" add -A
git -C "$work" -c user.name="Claude" -c user.email="noreply@anthropic.com" commit -qm "Pictures for #$issue"
git -C "$work" push -q origin "HEAD:refs/heads/$branch"
body+=$'\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_'
gh api -X POST "repos/$repo/issues/$issue/comments" -f body="$body" --jq .html_url
